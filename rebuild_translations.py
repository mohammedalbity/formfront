def main():
    """الدالة الرئيسية لإعادة بناء ملف en.json"""
    
    # مسارات الملفات
    ar_file = '/home/mohammed/form/formio/src/locales/ar.json'
    en_file = '/home/mohammed/form/formio/src/locales/en.json'
    
    try:
        # قراءة الملف العربي للمرجعية
        with open(ar_file, 'r', encoding='utf-8') as f:
            ar_data = json.load(f)
        
        # إنشاء الترجمات الإنجليزية الجديدة
        en_data = create_english_translations()
        
        # كتابة الملف الإنجليزي الجديد
        with open(en_file, 'w', encoding='utf-8') as f:
            json.dump(en_data, f, ensure_ascii=False, indent=2)
        
        print("✅ تم إعادة بناء ملف en.json بنجاح!")
        print(f"📊 عدد المفاتيح في ar.json: {len(ar_data)} (تقريبي)")
        print(f"📊 عدد المفاتيح في en.json الجديد: تم إنشاء هيكل شامل")
        
        # التحقق من صحة JSON
        with open(en_file, 'r', encoding='utf-8') as f:
            json.load(f)
        print("✅ تم التحقق من صحة JSON للملف الجديد")
        
    except Exception as e:
        print(f"❌ خطأ في إعادة بناء الملف: {e}")
        return False
    
    return True

if __name__ == "__main__":
    main()
